#!/usr/bin/env python3
"""Generates lib/src/model/plural_rules.dart from the rule table of package:intl.

Why not `Intl.pluralLogic`: its CLDR operands are computed incorrectly for a
fractional number (the integer part `i` is `n.round()`, so 1.5 gets i = 2 and
0.5 gets i = 1; the fractional part `f` comes from double arithmetic). The
rules themselves (the conditions) are correct in intl, so they are taken as
they are, but with operands supplied by us: (n, i, v, f, t).

Usage: python3 tool/generate_plural_rules.py [path to intl/lib/src/plural_rules.dart]
The output is unformatted: run `dart format lib/src/model/plural_rules.dart`
afterwards. Regenerate when the intl version changes; test/clarified_95_test.dart compares the
generated rules with intl itself on whole numbers.
"""
import re, sys, pathlib

default = pathlib.Path.home() / '.pub-cache/hosted/pub.dev/intl-0.20.3/lib/src/plural_rules.dart'
src = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else default).read_text()

start = src.index('PluralCase _ast_rule()')
body = src[start:]
mapstart = body.index('final pluralRules = {')
rules, table = body[:mapstart], body[mapstart:]
table = table[:table.index('/// Do we have plural rules')]
rules = 'PluralCase _default_rule() => OTHER;\n\n' + rules

rules = re.sub(r'PluralCase (_\w+_rule)\(\)', r'String \1(num n, int i, int v, int f, int t)', rules)
rules = rules.replace('PluralCase _default_rule() => OTHER;', 'String _default_rule(num n, int i, int v, int f, int t) => \'other\';')
for a, b in (('_n', 'n'), ('_i', 'i'), ('_v', 'v'), ('_f', 'f'), ('_t', 't')):
    rules = re.sub(r'(?<![\w])' + a + r'(?![\w])', b, rules)
for case in ('ZERO', 'ONE', 'TWO', 'FEW', 'MANY', 'OTHER'):
    rules = re.sub(r'return ' + case + ';', "return '" + case.lower() + "';", rules)
rules = rules.replace('=> OTHER;', "=> 'other';")
# Lambdas such as List.generate(n, (i) => i + 1) shadow the parameter `i`; rename them.
rules = rules.replace('(i) => i + ', '(k) => k + ')
table = table.replace('final pluralRules = {', 'const Map<String, PluralRuleFn> kPluralRules = {')

out = f"""// GENERATED by tool/generate_plural_rules.py from package:intl plural_rules.dart.
// Do not edit by hand.
//
// The CLDR rule conditions are taken from intl verbatim; the operands (n, i, v, f, t) are passed by the
// caller, because intl computes them wrongly for a fractional number (i = n.round()).

// ignore_for_file: prefer_single_quotes, unnecessary_parenthesis, non_constant_identifier_names, unnecessary_brace_in_string_interps, unused_element, curly_braces_in_flow_control_structures

/// A plural rule over CLDR operands: n is the absolute value, i the integer part, v the number of
/// visible digits after the decimal point, f the fractional part with those digits, t the same without
/// trailing zeros.
typedef PluralRuleFn = String Function(num n, int i, int v, int f, int t);

{rules}{table}"""
pathlib.Path('lib/src/model/plural_rules.dart').write_text(out)
